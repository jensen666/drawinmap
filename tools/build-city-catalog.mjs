/** 同名城市去重所需的省份后缀已在 id 里体现；这里校验 id 与简名唯一 */
function validate(rows) {
  const errors = [];
  const ids = new Map();
  const labels = new Map();
  const fullNames = new Map();
  for (const [id, label, province, lat, lng, isMunicipality] of rows) {
    if (ids.has(id)) {
      errors.push(`城市 id 重复：${id}`);
    }
    ids.set(id, true);
    if (labels.has(label)) {
      errors.push(`城市简名重复：${label}`);
    }
    labels.set(label, true);
    const fullName = isMunicipality ? label : `${label}市`;
    if (fullNames.has(fullName)) {
      errors.push(`城市全名重复：${fullName}`);
    }
    fullNames.set(fullName, true);
    // 南海诸岛（三沙）在 16°N 一带，下界放宽到 3.5°N（曾母暗沙以南才算出界）
    if (!Number.isFinite(lat) || lat < 3.5 || lat > 54) {
      errors.push(`${id} 纬度可疑：${lat}`);
    }
    if (!Number.isFinite(lng) || lng < 73 || lng > 135) {
      errors.push(`${id} 经度可疑：${lng}`);
    }
  }
  const municipalities = rows.filter((row) => row[5] === 1).length;
  if (municipalities !== 4) {
    errors.push(`直辖市数量应为 4，实际 ${municipalities}`);
  }
  const prefectureCities = rows.length - municipalities;
  if (prefectureCities !== 293) {
    errors.push(`地级市数量应为 293，实际 ${prefectureCities}`);
  }
  return errors;
}

const errors = validate(CITIES);
if (errors.length > 0) {
  console.error('[catalog] 校验失败：');
  for (const error of errors) {
    console.error(`  - ${error}`);
  }
  process.exit(1);
}

/** 简名 → 提示词/解析用城市名列表：全名 + 简名 + "×市"后缀（直辖市也要能认"北京市"） */
function cityNames(label, isMunicipality) {
  const fullName = isMunicipality ? label : `${label}市`;
  const names = [...new Set([fullName, label, `${label}市`])];
  return names;
}

const cities = CITIES.map(([id, label, province, lat, lng, isMunicipality]) => ({
  id,
  label,
  fullName: isMunicipality ? label : `${label}市`,
  names: cityNames(label, isMunicipality),
  province,
  preset: id === PRESET_CITY_ID,
  center: { lat: Math.round(lat * 10000) / 10000, lng: Math.round(lng * 10000) / 10000 },
}));

const catalog = {
  version: 1,
  presetCityId: PRESET_CITY_ID,
  /** 获取 bbox 从 center 推导：±(0.055° 纬度, 0.070° 经度)，与广州现网数据同尺度 */
  fetchHalfSpanDeg: { lat: 0.055, lng: 0.07 },
  cities,
};

